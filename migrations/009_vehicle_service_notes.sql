-- Adds a permanent, vehicle-level service-notes log — distinct from
-- BOTH the per-visit `problem` field on `cars` and the per-transition
-- `status_history` table. A service note records real maintenance work
-- done ("Front brake pads replaced at 186,100 km"), always with a
-- mandatory mileage reading, independent of whatever status the vehicle
-- happens to be in when it's recorded.
--
-- NOT applied by this file running — per project convention, this is
-- written for review and must be run manually in the Supabase SQL
-- editor (or via `psql`) after explicit approval. No DDL execution
-- capability exists from the application side.
--
-- Purely additive: one new table, no existing table/column touched.
--
-- IMPORTANT SCOPING NOTE (read before relying on this for multi-visit
-- history): this schema does not yet have a separate "physical vehicle"
-- entity independent of "the current service engagement" — that split
-- was proposed in an earlier planning phase but has not been approved
-- or implemented. Today, one `cars` row IS the vehicle for as long as
-- that row exists. These notes are scoped to `car_id` accordingly, so
-- they correctly survive status changes, delivery, cancellation, and
-- archival of THAT row — but if the same physical vehicle later returns
-- and is entered as a brand-new `cars` row (today's existing, already-
-- tolerated behavior for a repeat visit — see admin.js's duplicate-
-- registration handling), its notes do not automatically carry over to
-- the new row. True persistence across repeat visits requires the
-- vehicle-profile/visit model, which remains a separate, unapproved
-- decision.

create table if not exists vehicle_service_notes (
    id bigint generated by default as identity primary key,
    car_id bigint not null references cars(id) on delete cascade,
    company_id bigint not null references companies(id) on delete cascade,
    mileage_km integer not null,
    note text not null,
    created_by_admin_id bigint null references admin_accounts(id) on delete set null,
    created_at timestamptz not null default now(),

    constraint vehicle_service_notes_mileage_non_negative check (mileage_km >= 0)
);

-- company_id is denormalized (derivable via car_id -> cars.company_id)
-- on purpose, matching every other table in this schema (customers,
-- cars, workshop_telegram_groups, saved_media, telegram_connect_tokens)
-- — every row is directly tenant-scoped without needing a join, and
-- every admin.js query filters on it exactly like every other table.
create index if not exists vehicle_service_notes_car_id_idx on vehicle_service_notes (car_id);
create index if not exists vehicle_service_notes_company_id_idx on vehicle_service_notes (company_id);

-- created_by_admin_id is nullable and ON DELETE SET NULL (not CASCADE):
-- deleting an admin account must never delete the historical service
-- record of work that admin performed — the note simply becomes
-- "recorded by: (unknown)" rather than disappearing. "the staff/admin
-- who recorded it when that identity is available" (see admin.js) is
-- precisely this nullable column.

-- Application-level mileage validation (missing/negative/non-numeric
-- input rejected before this table is ever touched) lives in
-- admin.js's POST /admin/car/:id/notes — the CHECK constraint above is
-- a second, DB-level backstop for the one rule simple enough to encode
-- directly (mileage >= 0), consistent with how little else in this
-- schema uses CHECK constraints; it is not a substitute for the
-- richer "must be a whole number" validation the application performs.
