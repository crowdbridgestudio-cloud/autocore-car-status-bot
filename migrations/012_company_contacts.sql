-- Company-scoped contact people (owner, manager, etc.) that the
-- CUSTOMER-facing bot's "Contact Service" button can message directly —
-- distinct from `customers` (a customer's own contact info) and
-- distinct from the per-customer `contact_method`/`telegram_username`
-- added in migrations 010/011, which describe how to reach a CUSTOMER,
-- never a workshop's own staff. Reusing those fields for this purpose
-- was explicitly out of scope — they mean something different.
--
-- A plain new table (not two fixed columns on `companies` for "owner"
-- and "manager") because the requirement is genuinely one-to-many:
-- "support multiple contact people when the architecture can
-- accommodate this cleanly" — one row per person is the direct way to
-- do that without an arbitrary cap or admin UI changes every time a
-- shop wants a third contact.
--
-- NOT applied by this file running — manual Supabase SQL editor step,
-- same as every other migration in this project; no DDL execution
-- capability exists from the application side.
--
-- Purely additive: one new table, no existing table/column touched.
-- Does not modify migrations 009, 010, or 011 in any way.

create table if not exists company_contacts (
    id bigint generated by default as identity primary key,
    company_id bigint not null references companies(id) on delete cascade,
    role_label text not null,
    phone text null,
    telegram_username text null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists company_contacts_company_id_idx on company_contacts (company_id);

-- phone and telegram_username are BOTH optional ("do not force the
-- service to have both contact methods") — a contact can have one,
-- the other, both, or (temporarily, while being set up) neither.
-- role_label is required: showing a contact with no name/role at all
-- would be meaningless to a customer, and this is the one field that
-- has to be meaningful for the row to be worth displaying at all.
--
-- Validation of phone (WhatsApp-normalizable) and telegram_username
-- (Telegram-compatible username format) happens at the application
-- layer (utils.js's toWhatsappDigits / sanitizeTelegramUsername, shared
-- by admin.js, superadmin.js, and index.js) — consistent with how this
-- schema already handles richer validation elsewhere (VIN, mileage)
-- rather than encoding it in a CHECK constraint.
